package main

import "fmt"

// ТЗ:
// 1) Напиши функцию swap(a, b *int), которая меняет местами значения двух переменных.
// 2) Используй только указатели внутри функции swap.
// 3) В main создай переменные x и y.
// 4) Выведи значения x и y до и после вызова swap(&x, &y).
// 5) Ожидаемый итог: значения x и y успешно поменялись местами.
func swap(a, b *int) {
	temp := *a
	*a = *b
	*b = temp
}

func main() {
	x, y := 10, 25

	fmt.Printf("До:    x = %d, y = %d\n", x, y)
	swap(&x, &y)
	fmt.Printf("После: x = %d, y = %d\n", x, y)
}

// Оценка: 5/5 — задание выполнено корректно.

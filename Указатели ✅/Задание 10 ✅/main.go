package main

import "fmt"

// ТЗ:
// 1) Создай переменную n со значением 12 и указатель p на нее.
// 2) Выведи типы и значения: тип n и его значение, тип p и его адрес, значение по адресу *p.
// 3) Используй fmt.Printf с форматами %T, %d и %p.
// 4) Измени значение через указатель: *p = 25.
// 5) Выведи итоговое значение n (ожидается 25).

func main() {
	n := 12
	p := &n

	fmt.Printf("n: type=%T, value=%d\n", n, n)
	fmt.Printf("p: type=%T, value=%p\n", p, p)
	fmt.Printf("*p: type=%T, value=%d\n", *p, *p)

	*p = 25

	fmt.Printf("После изменения через указатель n=%d\n", n)
}


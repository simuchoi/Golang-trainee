package main

import "fmt"

// ТЗ:
// 1) Создай переменную n со значением 7.
// 2) Напиши функцию inc(p *int), которая увеличивает число на 1 через указатель.
// 3) В main выведи значение n до и после вызова inc(&n).
// 4) Для вывода используй fmt.Printf.
// 5) Ожидаемый итог: после вызова n = 8.

func main() {
	n := 7

	fmt.Printf("n before: %d\n", n)

	inc(&n)

	fmt.Printf("n after: %d\n", n)
}

func inc(p *int) {
	*p++
}

